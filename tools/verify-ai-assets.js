// verify-ai-assets.js — post-build gate for the AI-readable surfaces.
//
// Reads only files under public/ and public/llms.txt etc., so it fails on what
// a crawler or a reader would actually receive. Run after `hexo generate`.
// Exit code 1 on any failure; every check prints pass/fail lines.
'use strict'

const fs = require('fs')
const path = require('path')

const ROOT = path.resolve(__dirname, '..')
const PUBLIC = path.join(ROOT, 'public')
const SITE = 'https://speechlesspanda.github.io'

const failures = []
const passes = []

function check (name, fn) {
  try {
    const detail = fn()
    passes.push(`✓ ${name}${detail ? ' — ' + detail : ''}`)
  } catch (err) {
    failures.push(`✗ ${name} — ${err.message}`)
  }
}

function assert (condition, message) {
  if (!condition) throw new Error(message)
}

function read (file) {
  return fs.readFileSync(path.join(PUBLIC, file), 'utf8')
}

function exists (file) {
  return fs.existsSync(path.join(PUBLIC, file))
}

function decode (urlPath) {
  try {
    return decodeURI(urlPath)
  } catch {
    return urlPath
  }
}

function toFile (url) {
  return path.join(PUBLIC, decode(url.replace(/^https?:\/\/[^/]+/, '')))
}

const robots = read('robots.txt')
const sitemap = read('sitemap.xml')
const llms = read('llms.txt')
const siteIndex = read('index.html')

const sitemapLocs = [...sitemap.matchAll(/<loc>([^<]+)<\/loc>/g)].map(m => m[1])
const sitemapLastmods = [...sitemap.matchAll(/<url>\s*<loc>([^<]+)<\/loc>\s*<lastmod>([^<]+)<\/lastmod>/g)]

// --- robots.txt -----------------------------------------------------------

check('robots.txt is a single generated source', () => {
  assert(/generated by scripts\/ai\/robots\.js/.test(robots), 'missing generation header')
  const wildcards = (robots.match(/^User-agent: \*$/gm) || []).length
  assert(wildcards === 1, 'expected exactly one wildcard group, got ' + wildcards)
  assert(!/<html|<head|plugin/i.test(robots), 'robots.txt looks like concatenated plugin output')
  assert(/^Sitemap: /m.test(robots), 'sitemap line missing')
})

check('robots.txt expresses no-training via both draft signals', () => {
  assert(/^User-agent: __usage_ai-training$/m.test(robots), 'missing policy token group')
  assert(/^Content-Usage: train-ai=n$/m.test(robots), 'missing AIPREF Content-Usage preference')
  assert(/draft|Internet-Draft|草案/.test(robots), 'draft status must be stated')
})

check('robots.txt admits search + AI search crawlers and blocks memos', () => {
  for (const bot of ['Googlebot', 'Bingbot', 'OAI-SearchBot', 'ChatGPT-User', 'Claude-SearchBot', 'Claude-User', 'PerplexityBot']) {
    const group = robots.split(/\n\s*\n/).find(g => new RegExp(`^User-agent: ${bot}$`, 'm').test(g))
    assert(group, `${bot} missing`)
    assert(/^Allow: \/$/m.test(group), `${bot} not allowed`)
    assert(/^Disallow: \/memos\/$/m.test(group), `${bot} may crawl memos`)
  }
  assert(/^Sitemap: https:\/\/speechlesspanda\.github\.io\/sitemap\.xml$/m.test(robots), 'sitemap line missing')
})

// --- sitemap.xml ----------------------------------------------------------

check('sitemap.xml has absolute canonical HTTPS locs', () => {
  assert(sitemapLocs.length > 20, 'too few locs: ' + sitemapLocs.length)
  for (const loc of sitemapLocs) {
    assert(/^https:\/\/speechlesspanda\.github\.io\//.test(loc), 'non-absolute or http loc: ' + loc)
    assert(!/\/$/.test(loc), 'loc is a directory URL, expected canonical index.html: ' + loc)
  }
  assert(new Set(sitemapLocs).size === sitemapLocs.length, 'duplicate locs')
})

check('sitemap.xml excludes drafts, mirrors, memos, 404 and pagination', () => {
  for (const loc of sitemapLocs) {
    assert(!/\/_drafts\//.test(loc), 'draft in sitemap: ' + loc)
    assert(!/\.md$/.test(loc), 'mirror in sitemap: ' + loc)
    assert(!/\/memos\//.test(loc), 'memos in sitemap: ' + loc)
    assert(!/404/.test(loc), '404 in sitemap: ' + loc)
    assert(!/\/page\/\d+\//.test(loc), 'pagination duplicate in sitemap: ' + loc)
  }
})

check('every sitemap loc matches the page canonical and exists', () => {
  assert(sitemapLastmods.length === sitemapLocs.length, 'every <url> must carry <lastmod>')
  for (const loc of sitemapLocs) {
    const file = toFile(loc)
    assert(fs.existsSync(file), 'no such file: ' + loc)
    const html = fs.readFileSync(file, 'utf8')
    const canonical = /<link rel="canonical" href="([^"]+)"/.exec(html)
    assert(canonical, 'missing canonical: ' + loc)
    assert(canonical[1] === loc, `canonical mismatch: ${canonical[1]} != ${loc}`)
  }
})

check('sitemap lastmod is a real date, not the build clock', () => {
  const today = new Date().toISOString().slice(0, 10)
  let todayCount = 0
  for (const [, , lastmod] of sitemapLastmods) {
    assert(/^\d{4}-\d{2}-\d{2}$/.test(lastmod), 'bad lastmod format: ' + lastmod)
    if (lastmod === today) todayCount++
  }
  // A build-clock bug stamps every entry with today's date. Genuinely new pages
  // added today are allowed, but they can never dominate the sitemap.
  assert(todayCount <= 2 && todayCount / sitemapLastmods.length < 0.1,
    `${todayCount}/${sitemapLastmods.length} lastmod values equal today's build date`)
})

// --- discovery links -----------------------------------------------------

const postFiles = []
function walk (dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) walk(full)
    else if (entry.name === 'index.html') postFiles.push(full)
  }
}
walk(PUBLIC)

const postHtml = postFiles.filter(file => {
  const rel = path.relative(PUBLIC, file).split(path.sep).join('/')
  return /^_?posts|^\d{4}\/|^series\//.test(rel) && !rel.startsWith('memos/')
})

check('every article/series HTML links its Markdown mirror + llms.txt', () => {
  const missing = []
  for (const file of postHtml) {
    const html = fs.readFileSync(file, 'utf8')
    const rel = path.relative(PUBLIC, file).split(path.sep).join('/')
    if (!extractPostPath(html)) continue // listing pages under /series/ etc.
    const alt = /<link rel="alternate" type="text\/markdown" href="([^"]+)">/.exec(html)
    const described = /<link rel="describedby" href="([^"]+)">/.exec(html)
    if (!alt) { missing.push(rel + ' (alternate)'); continue }
    if (!described) { missing.push(rel + ' (describedby)'); continue }
    if (described[1] !== '/llms.txt') { missing.push(rel + ' (describedby target)'); continue }
    const mirror = toFile(alt[1])
    if (!fs.existsSync(mirror)) missing.push(rel + ' (mirror file)')
  }
  assert(missing.length === 0, missing.slice(0, 5).join('; '))
  return `${postHtml.length} pages`
})

function extractPostPath (html) {
  const canonical = /<link rel="canonical" href="([^"]+)"/.exec(html)
  return canonical ? canonical[1] : ''
}

// --- Markdown mirrors -----------------------------------------------------

function frontMatter (markdown) {
  const match = /^---[ \t]*\r?\n[\s\S]*?\r?\n---[ \t]*(?:\r?\n|$)/.exec(markdown)
  return match ? match[0] : ''
}

const mirrorFiles = postFiles
  .map(file => file.replace(/index\.html$/, 'index.md'))
  .filter(file => fs.existsSync(file) && !path.relative(PUBLIC, file).startsWith('memos'))

check('every mirror has title + canonical + license metadata', () => {
  const bad = []
  for (const file of mirrorFiles) {
    const markdown = fs.readFileSync(file, 'utf8')
    const rel = path.relative(PUBLIC, file).split(path.sep).join('/')
    if (!/^# /.test(markdown)) bad.push(rel + ' (title)')
    if (!/原文（HTML）：https:\/\/speechlesspanda\.github\.io\//.test(markdown)) bad.push(rel + ' (canonical)')
    if (!/CC BY-NC-SA 4\.0/.test(markdown)) bad.push(rel + ' (license)')
    if (frontMatter(markdown)) bad.push(rel + ' (front matter left in)')
  }
  assert(bad.length === 0, bad.slice(0, 5).join('; '))
  return `${mirrorFiles.length} mirrors`
})

check('mirrors preserve code fences, tables and math parity with source', () => {
  const bad = []
  for (const file of mirrorFiles) {
    const rel = path.relative(PUBLIC, file).split(path.sep).join('/')
    const mirror = fs.readFileSync(file, 'utf8')
    // Source is the public mirror route's HTML: compare against its _content?
    // Simpler and stricter: check internal balance of structures in the mirror.
    const fences = (mirror.match(/^\s*(```|~~~)/gm) || []).length
    if (fences % 2 !== 0) bad.push(rel + ' (fence balance)')
    const dollars = (mirror.match(/\$\$/g) || []).length
    if (dollars % 2 !== 0) bad.push(rel + ' (math balance)')
    const tableRows = mirror.split(/\r?\n/).filter(line => /^\s*\|/.test(line)).length
    const separators = (mirror.match(/^\s*\|(?:\s*:?-{2,}:?\s*\|)+\s*$/gm) || []).length
    if (separators > 0 && tableRows < separators) bad.push(rel + ' (table rows)')
    assert(!/\{%\s*(hideToggle|endhideToggle)/.test(mirror), rel + ' (theme tag leaked)')
  }
  assert(bad.length === 0, bad.slice(0, 5).join('; '))
})

check('article mirrors keep the body text, not just the header', () => {
  const bad = []
  for (const file of mirrorFiles) {
    const rel = path.relative(PUBLIC, file).split(path.sep).join('/')
    if (rel.startsWith('series/')) continue // series landings are chapter lists, checked below
    const mirror = fs.readFileSync(file, 'utf8')
    const body = mirror.replace(/^[^\n]*\n(?:>[^\n]*\n)+/, '')
    const htmlFile = file.replace(/index\.md$/, 'index.html')
    if (!fs.existsSync(htmlFile)) { bad.push(rel + ' (no html)'); continue }
    const html = fs.readFileSync(htmlFile, 'utf8')
    const start = html.indexOf('id="article-container"')
    const endMarker = html.indexOf('<div class="tag_share"', start)
    const article = html.slice(start, endMarker === -1 ? undefined : endMarker)
    const plain = article
      .replace(/<td class="gutter">[\s\S]*?<\/td>/g, '')
      .replace(/<[^>]+>/g, '')
      .replace(/\s+/g, '')
    const mirrorPlain = body.replace(/\s+/g, '')
    if (plain.length > 500 && mirrorPlain.length < plain.length * 0.5) {
      bad.push(`${rel} (${mirrorPlain.length}/${plain.length})`)
    }
  }
  assert(bad.length === 0, bad.slice(0, 5).join('; '))
})

check('series mirrors list every chapter mirror', () => {
  const bad = []
  for (const file of mirrorFiles) {
    const rel = path.relative(PUBLIC, file).split(path.sep).join('/')
    if (!rel.startsWith('series/')) continue
    const mirror = fs.readFileSync(file, 'utf8')
    const htmlFile = file.replace(/index\.md$/, 'index.html')
    const html = fs.readFileSync(htmlFile, 'utf8')
    // Chapter titles appear as links on the landing page; each must have a
    // corresponding mirror link in the series mirror.
    const links = [...mirror.matchAll(/\]\(([^)]+index\.md)\)/g)].map(m => m[1])
    if (links.length === 0) { bad.push(rel + ' (no chapter links)'); continue }
    for (const link of links) {
      if (!fs.existsSync(toFile(link))) bad.push(rel + ' -> ' + link)
    }
    if (!/^## 章节$/m.test(mirror)) bad.push(rel + ' (missing chapter heading)')
  }
  assert(bad.length === 0, bad.slice(0, 5).join('; '))
  return 'series mirrors link built chapter files'
})

// --- llms.txt -------------------------------------------------------------

const llmsLinks = [...llms.matchAll(/\]\(([^)]+)\)/g)].map(m => m[1]).filter(link => link.startsWith('/'))

check('llms.txt structure: H1, blockquote, H2 sections', () => {
  const lines = llms.split(/\r?\n/)
  assert(/^# \S/.test(lines[0]), 'first line must be H1')
  assert(lines.slice(1, 6).some(line => /^> /.test(line)), 'blockquote summary missing')
  const sections = lines.filter(line => /^## /.test(line))
  for (const required of ['关于本站', '主题索引', '精选文章', '系列与章节', '版权与 AI 使用偏好']) {
    assert(sections.some(line => line.includes(required)), 'missing H2: ' + required)
  }
  assert(sections.length >= 5, 'too few H2 sections')
})

check('llms.txt has 8 featured entries with summaries and mirrors', () => {
  const section = sectionOf(llms, '精选文章')
  const entries = section.split(/\r?\n/).filter(line => /^- \[/.test(line))
  assert(entries.length === 8, 'expected 8 featured entries, got ' + entries.length)
  for (const entry of entries) assert(/）：\S/.test(entry), 'featured entry without summary: ' + entry.slice(0, 40))
  const mirrors = section.split(/\r?\n/).filter(line => /^\s+- Markdown: \//.test(line))
  assert(mirrors.length === 8, 'expected 8 mirror links, got ' + mirrors.length)
})

check('every llms.txt link resolves to a built file', () => {
  const missing = []
  for (const link of llmsLinks) {
    const file = toFile(link.replace(/\(.*\)$/, '').split('#')[0])
    if (!fs.existsSync(file)) missing.push(link)
  }
  assert(missing.length === 0, missing.slice(0, 6).join('; '))
  return `${llmsLinks.length} links`
})

function sectionOf (text, title) {
  const start = text.indexOf('## ' + title)
  if (start === -1) throw new Error('missing section ' + title)
  const next = text.indexOf('\n## ', start + 3)
  return text.slice(start, next === -1 ? undefined : next)
}

// --- home icon + /ai/ page ------------------------------------------------

check('home Follow Me row shows GitHub → Email → RSS → AI with accessible label', () => {
  const block = /Follow Me[\s\S]{0,1200}?<\/div>/.exec(siteIndex)
  assert(block, 'Follow Me block missing')
  const tags = [...block[0].matchAll(/<a class="social-icon"[^>]*>/g)].map(m => m[0])
  const order = tags.map(tag => /href="([^"]+)"/.exec(tag)[1])
  const expected = ['https://github.com/SpeechlessPanda', 'mailto:zhoushimingyu@qq.com', '/atom.xml', '/ai/']
  assert(JSON.stringify(order) === JSON.stringify(expected), 'icon order is ' + JSON.stringify(order))
  const unlabeled = tags.filter(tag => !/aria-label="[^"]+"/.test(tag))
  assert(unlabeled.length === 0, 'social icon without aria-label: ' + unlabeled[0])
  assert(/aria-label="AI 阅读入口"/.test(block[0]), 'AI icon lacks aria-label')
  assert(/fas fa-robot/.test(block[0]), 'AI icon must reuse fas fa-robot')
})

check('/ai/ page exists, is indexable and links every machine entry', () => {
  const file = path.join(PUBLIC, 'ai', 'index.html')
  assert(fs.existsSync(file), '/ai/ not generated')
  const html = fs.readFileSync(file, 'utf8')
  assert(!/<meta name="robots" content="noindex/i.test(html), '/ai/ must be indexable')
  for (const link of ['/llms.txt', '/sitemap.xml', '/robots.txt', '/atom.xml', '/rights/']) {
    assert(html.includes('href="' + link + '"'), '/ai/ missing link to ' + link)
  }
  assert(/AI 阅读/.test(html), 'title missing')
  assert(/<div class="ai-guide">/.test(html), 'guide content missing')
  assert(sitemapLocs.some(loc => loc.endsWith('/ai/index.html')), '/ai/ not in sitemap')
})

check('/rights/ page states license, AI preference and crawler rules', () => {
  const file = path.join(PUBLIC, 'rights', 'index.html')
  assert(fs.existsSync(file), '/rights/ not generated')
  const html = fs.readFileSync(file, 'utf8')
  for (const needle of ['CC BY-NC-SA 4.0', 'train-ai=n', '__usage_ai-training', 'robots.txt', '训练']) {
    assert(html.includes(needle), '/rights/ missing ' + needle)
  }
})

// --- surfaces agree with each other --------------------------------------

check('robots.txt, sitemap and mirrors agree on the same site', () => {
  assert(robots.includes(SITE + '/sitemap.xml'), 'robots sitemap URL mismatch')
  assert(llms.includes('/llms.txt') === false, 'llms.txt should not link itself as a section item')
  assert(fs.existsSync(path.join(PUBLIC, 'llms.txt')), 'llms.txt missing')
  assert(fs.existsSync(path.join(PUBLIC, 'baidusitemap.xml')), 'baidusitemap.xml was removed')
  assert(fs.existsSync(path.join(PUBLIC, 'search.xml')), 'search.xml vanished')
})

check('memos stay noindex and out of AI surfaces', () => {
  const memoPages = postFiles.filter(file => path.relative(PUBLIC, file).split(path.sep)[0] === 'memos')
  assert(memoPages.length > 0, 'expected memo pages')
  for (const file of memoPages.slice(0, 3)) {
    const html = fs.readFileSync(file, 'utf8')
    assert(/<meta name="robots" content="noindex/.test(html), 'memo page not noindex: ' + file)
  }
  assert(!sitemapLocs.some(loc => loc.includes('/memos/')), 'memos leaked into sitemap')
  assert(!/\]\(\/memos\//.test(llms), 'memos leaked into llms.txt')
})

check('search index still contains article entries', () => {
  const search = read('search.xml')
  const entries = (search.match(/<entry>/g) || []).length
  assert(entries >= 25, 'search index shrank: ' + entries)
})

