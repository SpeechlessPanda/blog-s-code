// robots.txt — single generated source, replaces hexo-generator-robotstxt
// (same generator id; site scripts load after plugins, so this one wins).
// The `robotstxt:` block was removed from _config.yml with it.
//
// Policy encoded here:
//   * ordinary search engines may crawl everything public;
//   * AI search / user-triggered fetchers may crawl (their answers link back);
//   * training-only crawlers get an explicit "no training" preference.
//
// Two machine-readable signals, both Internet-Draft drafts rather than standards:
//   - the cross-vendor policy token `__usage_ai-training` from
//     draft-kelley-aipref-training-preference-signal-01 (a robots group keyed by
//     the token; Disallow means "preference against", Allow means "in favour");
//   - the AIPREF robots extension `Content-Usage: train-ai=n` from
//     draft-ietf-aipref-attach-05 (a usage preference, not a crawl directive).
//
// Product tokens follow each vendor's published bot documentation as of
// 2026-11. Every token is listed separately instead of pattern-globbing so the
// file stays auditable and a vendor rename is a visible diff.
'use strict'

const { siteUrl } = require('./lib/util')

// Crawlers whose fetched content feeds generative-model training.
const TRAINING_CRAWLERS = [
  'GPTBot', // OpenAI training crawler
  'ClaudeBot', // Anthropic training crawler
  'Google-Extended', // Gemini training/grounding opt-out token (no own crawler)
  'Applebot-Extended', // Apple foundation-model training opt-out token
  'CCBot', // Common Crawl corpus, widely used for training
  'Bytespider', // ByteDance / TikTok crawler
  'meta-externalagent', // Meta AI training crawler
  'Amazonbot', // Amazon AI training crawler
  'cohere-ai', // Cohere training crawler
  'ImagesiftBot', // image training corpus
  'Omgili', // web data reseller
  'TimpiBot', // search/data reseller crawler
  'DuckAssistBot' // DuckDuckGo assistant corpus
]

// AI search crawlers: they index for retrieval systems whose answers cite and
// link the source, so they are treated like search engines.
const AI_SEARCH_CRAWLERS = [
  'OAI-SearchBot', // ChatGPT Search
  'ChatGPT-User', // user-triggered fetch in ChatGPT
  'Claude-SearchBot', // Claude search index
  'Claude-User', // user-triggered fetch in Claude
  'PerplexityBot', // Perplexity search index
  'Perplexity-User', // user-triggered fetch in Perplexity
  'Googlebot',
  'Bingbot',
  'DuckDuckBot',
  'Baiduspider',
  'YandexBot'
]

// Mirrors of a disallowed resource would otherwise be crawlable while the
// canonical HTML is not, so the preference applies to everything except these
// helper files.
const TRAINING_ALLOWED_PATHS = ['/llms.txt', '/robots.txt', '/sitemap.xml']

// Client-rendered timeline whose per-item pages are noindex.
const PRIVATE_PATHS = ['/memos/']

const TRAIN_NONE = 'Content-Usage: train-ai=n'

function group (agents, lines) {
  return agents.map(agent => [`User-agent: ${agent}`, ...lines].join('\n')).join('\n\n')
}

function generate (hexo) {
  const base = siteUrl(hexo)
  const privateLines = PRIVATE_PATHS.map(path => `Disallow: ${path}`)

  const sections = [
    '# robots.txt — generated by scripts/ai/robots.js; do not edit by hand.',
    `# 版权与内容使用政策: ${base}/rights/`,
    `# 给 AI 的机器入口: ${base}/llms.txt`,
    '#',
    '# 搜索引擎与 AI 搜索/用户触发抓取: 允许。',
    '# 训练用途: 表达"不训练"偏好。以下信号来自 Internet-Draft 草案,',
    '# 不是标准,也不构成法律许可或对版权许可的修改。',
    '',
    '# --- 通用规则: 允许抓取,排除碎碎念时间线 ---',
    group(['*'], ['Allow: /', ...privateLines, TRAIN_NONE]),
    '',
    '# --- 训练偏好 token(AIPREF 草案): Disallow = 不希望用于训练 ---',
    group(['__usage_ai-training'], [
      'Disallow: /',
      ...TRAINING_ALLOWED_PATHS.map(path => `Allow: ${path}`),
      ...privateLines
    ]),
    '',
    '# --- 训练爬虫: 不训练偏好 ---',
    group(TRAINING_CRAWLERS, ['Disallow: /', ...TRAINING_ALLOWED_PATHS.map(path => `Allow: ${path}`), ...privateLines, TRAIN_NONE]),
    '',
    '# --- AI 搜索与用户触发抓取: 允许,仅排除碎碎念 ---',
    group(AI_SEARCH_CRAWLERS, ['Allow: /', ...privateLines]),
    '',
    `Sitemap: ${base}/sitemap.xml`,
    ''
  ]
  return sections.join('\n')
}

hexo.extend.generator.register('robotstxt', function () {
  return { path: 'robots.txt', data: generate(this) }
})

module.exports = { generate, TRAINING_CRAWLERS, AI_SEARCH_CRAWLERS, PRIVATE_PATHS }
